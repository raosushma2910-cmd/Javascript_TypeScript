//string literal
let age = "Sushma"; 
let age2 = 'Sushma';
console.log(typeof age);
console.log(typeof age2);

//boolean literal
let isStudent = true;
let isWorking = false;
console.log(typeof isStudent);
console.log(typeof isWorking);

//number literal
let num1 = 10;
let num2 = 10.5;
console.log(typeof num1);
console.log(typeof num2);

//null literal
let a = null; // null means nothing (it is an object type)
console.log(typeof a); 

let b = undefined; 
console.log(typeof b); // its value is undefined






